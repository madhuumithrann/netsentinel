"""TCP reset analysis.

Objective
    Explain *why* connections are being reset instead of counting RST packets.

Algorithm (per reconstructed connection, see ``context.connections``)
    * refused  - the client sent SYN, the server never sent SYN/ACK and answered with RST.
                 Nothing is listening on that port, or a firewall rejects it.
    * aborted  - the connection was established and a RST arrived before both sides sent FIN.
    * closing  - RST after a FIN, or a client RST at the end of a finished exchange. Browsers
                 and many applications close like this on purpose, so it is NOT reported.

    Refusals are grouped per service (server IP + port), aborts per server endpoint and the
    side that sent the reset. A port scan produces one refusal per port, so the
    ``refused_min_per_service`` threshold stops scans from being reported as service outages
    (the scan detector reports them instead).

Injected-reset indicator
    A RST whose IP TTL differs by 5 or more from the TTL of the other packets that endpoint
    sent in the same connection was probably not sent by that endpoint (on-path injection,
    or a middlebox resetting on its behalf).

Limitations
    The capture point decides what we see: a RST generated by a firewall between the capture
    point and the server looks exactly like a server RST unless its TTL differs.
"""
from __future__ import annotations

from collections import defaultdict
from statistics import median

from ..context import AnalysisContext, TcpConnection
from ..model import ACK, ATTACK, BENIGN, FAULT, FIN, SYN, Evidence, Finding, Indicator, assess

NAME = "tcp_resets"


def _classify(conn: TcpConnection) -> list[tuple[str, object]]:
    """Return (kind, rst_packet) for every reset in the connection."""
    out = []
    for rst in conn.resets:
        before = [p for p in conn.packets if p.n < rst.n]
        fin_before = any(p.tcp_flags & FIN for p in before)
        synack_before = any(p.tcp_flags & SYN and p.tcp_flags & ACK for p in before)
        from_server = not conn.from_client(rst)
        if conn.syns and not synack_before and from_server:
            out.append(("refused", rst))
        elif fin_before:
            out.append(("closing", rst))
        elif conn.established or synack_before:
            # A client reset after it already received the full response is a normal abort.
            last_data = max((p.n for p in before if p.payload_len), default=None)
            client_ends = conn.from_client(rst) and last_data is not None and \
                not any(p.payload_len for p in conn.packets if p.n > rst.n)
            if client_ends and before and not before[-1].payload_len and conn.server_bytes:
                out.append(("closing", rst))
            else:
                out.append(("aborted", rst))
        else:
            out.append(("other", rst))
    return out


def _ttl_outlier(conn: TcpConnection, rst) -> int | None:
    same_side = [p.ttl for p in conn.packets
                 if p is not rst and (p.ip_src, p.sport) == (rst.ip_src, rst.sport) and p.ttl is not None]
    if len(same_side) < 2 or rst.ttl is None:
        return None
    typical = median(same_side)
    return int(typical) if abs(rst.ttl - typical) >= 5 else None


def detect(ctx: AnalysisContext) -> list[Finding]:
    th = ctx.thresholds
    refused: dict[tuple[str, int], list[tuple[TcpConnection, object]]] = defaultdict(list)
    aborted: dict[tuple[str, int, str], list[tuple[TcpConnection, object]]] = defaultdict(list)
    for conn in ctx.connections:
        if not conn.resets:
            continue
        for kind, rst in _classify(conn):
            if kind == "refused":
                refused[conn.server].append((conn, rst))
            elif kind == "aborted":
                side = "server" if not conn.from_client(rst) else "client"
                aborted[(conn.server[0], conn.server[1], side)].append((conn, rst))

    findings: list[Finding] = []

    for (server_ip, port), items in refused.items():
        if len(items) < th.refused_min_per_service:
            continue
        clients = sorted({c.client[0] for c, _ in items})
        evidence = []
        for conn, rst in items:
            evidence.extend(Evidence(s.n, "connection attempt (SYN)") for s in conn.syns[:1])
            evidence.append(Evidence(rst.n, "refusal (RST answering the SYN)"))
        times = [r.ts for _, r in items]
        indicators = [Indicator(f"{len(items)} connection attempts to {server_ip}:{port} were refused",
                                FAULT, "moderate"),
                      Indicator("The same service was requested repeatedly (normal client behaviour, "
                                "not probing many ports)", FAULT, "moderate")]
        findings.append(Finding(
            detector=NAME, kind="TCP_CONNECTION_REFUSED",
            title=f"Service {server_ip}:{port} is refusing connections",
            category="fault", assessment=assess(indicators), severity="medium",
            evidence_strength="strong" if len(items) >= 2 * th.refused_min_per_service else "moderate",
            summary=(f"{len(items)} attempts by {len(clients)} client(s) to connect to port {port} on "
                     f"{server_ip} were immediately rejected with a TCP reset. The server is reachable, "
                     "but nothing accepted the connection."),
            impact="Users of this service see 'connection refused' errors or an application that will not load.",
            likely_cause=("The service on that port is stopped, crashed, or listening on a different port; "
                          "or a host firewall is rejecting the port."),
            recommendations=[f"Check that the service expected on port {port} is running on {server_ip}.",
                             "Confirm the application listens on the expected port and interface "
                             "(for example with 'netstat -ano' on Windows or 'ss -ltnp' on Linux).",
                             "Check host and network firewall rules for this port."],
            facts=[f"{len(items)} SYN packets were answered by RST without any SYN/ACK.",
                   f"Clients involved: {', '.join(clients[:10])}" + (" ..." if len(clients) > 10 else "")],
            alternatives=["A firewall between the client and server may be sending the resets on the "
                          "server's behalf."],
            limitations=["The capture cannot show whether the reset came from the server itself or from "
                         "a device in front of it, unless the TTL differs."],
            indicators=indicators,
            hosts={"server": [server_ip], "client": clients},
            time_start=min(times), time_end=max(times), evidence=evidence,
            metrics={"refused_attempts": len(items), "clients": len(clients), "port": port},
            rule=f"RST answering SYN with no SYN/ACK, >= {th.refused_min_per_service} times for one service"))

    for (server_ip, port, side), items in aborted.items():
        if len(items) < th.aborted_min_per_peer:
            continue
        conns = {id(c): c for c, _ in items}
        injected = []
        for conn, rst in items:
            typical = _ttl_outlier(conn, rst)
            if typical is not None:
                injected.append((rst, typical))
        indicators = [Indicator(f"{len(conns)} established connections were cut off by a reset from the "
                                f"{side} side", FAULT, "moderate")]
        if injected:
            indicators.append(Indicator(
                f"{len(injected)} reset(s) carry an IP TTL different from every other packet of the same "
                "sender in that connection, so they were probably sent by a different device",
                ATTACK, "strong" if len(injected) >= 3 else "moderate"))
        elif side == "client":
            indicators.append(Indicator("Clients themselves ended the connections; applications often do "
                                        "this deliberately", BENIGN, "weak"))
        evidence = []
        for conn, rst in items:
            last_data = [p for p in conn.packets if p.n < rst.n and p.payload_len][-1:]
            evidence.extend(Evidence(p.n, "last data before the reset") for p in last_data)
            evidence.append(Evidence(rst.n, f"reset sent by the {side}"))
        for rst, typical in injected:
            evidence.append(Evidence(rst.n, f"reset with unusual TTL {rst.ttl} (sender normally uses {typical})"))
        times = [r.ts for _, r in items]
        clients = sorted({c.client[0] for c in conns.values()})
        assessment = assess(indicators)
        if injected:
            summary = (f"{len(conns)} connections to {server_ip}:{port} were cut off mid-session. "
                       f"{len(injected)} of the resets do not match the normal TTL of the endpoint they "
                       "claim to come from, which suggests they were forged by a device in the path.")
            cause = ("Possible TCP reset injection (a device in the path forging resets to tear down "
                     "connections), or a security appliance terminating sessions.")
        else:
            summary = (f"{len(conns)} established connections to {server_ip}:{port} were terminated abruptly "
                       f"by a reset from the {side} instead of closing normally.")
            cause = ("The server application crashed, restarted or hit a resource limit; a load balancer or "
                     "firewall timed the sessions out; or the client application aborted them."
                     if side == "server" else
                     "The client application aborted the connections (user cancelled, timeout, or "
                     "application error).")
        findings.append(Finding(
            detector=NAME, kind="TCP_CONNECTION_RESET",
            title=f"Connections to {server_ip}:{port} reset mid-session",
            category="fault", assessment=assessment,
            severity="high" if assessment == ATTACK else "medium" if side == "server" else "low",
            evidence_strength="strong" if injected else "moderate",
            summary=summary,
            impact="Downloads, pages or sessions fail part-way through and must be retried.",
            likely_cause=cause,
            recommendations=(["Compare the TTL of the resets with normal traffic from the same server and "
                              "trace which device sits at that hop distance.",
                              "Check for intrusion-prevention systems or unknown in-line devices.",
                              "Move sensitive traffic to encrypted, authenticated channels (TLS / VPN)."]
                             if injected else
                             ["Check the server application logs and resource usage at the times shown.",
                              "Check load balancer / firewall idle timeouts and session limits.",
                              "If only one client is affected, inspect that client application."]),
            facts=[f"{len(items)} RST packets ended established connections before a normal FIN close.",
                   f"Connections affected: {len(conns)}, clients: {', '.join(clients[:10])}"],
            alternatives=["Resets can be a deliberate design choice of some applications to close quickly."],
            limitations=["Without application logs, the capture cannot show why the endpoint reset."],
            indicators=indicators,
            hosts={"server": [server_ip], "client": clients},
            time_start=min(times), time_end=max(times), evidence=evidence,
            metrics={"aborted_connections": len(conns), "resets": len(items), "reset_by": side,
                     "ttl_mismatched_resets": len(injected), "port": port},
            rule=f"RST on an established connection before FIN, >= {th.aborted_min_per_peer} per server endpoint"))
    return findings
