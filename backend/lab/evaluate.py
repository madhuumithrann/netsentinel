"""Measure detection quality against the labelled synthetic scenarios.

    cd backend
    python -m lab.evaluate            # prints a Markdown report
    python -m lab.evaluate --write    # also writes docs/EVALUATION.md

Scoring is per scenario and per finding kind:
    TP  an expected kind was reported
    FN  an expected kind was not reported
    FP  a kind listed in the scenario's ``forbid`` set was reported, or a finding was assessed
        as an attack in a scenario marked ``forbid_attacks`` (benign or fault-only traffic)
    TN  a forbidden kind was correctly not reported
Kinds that are neither expected nor forbidden are listed as "unlabelled" and not scored.

These numbers describe behaviour on synthetic traffic written by the same team that wrote
the detectors. They show that each rule behaves as designed on its positive and negative
cases; they are NOT an estimate of real-world accuracy.
"""
from __future__ import annotations

import argparse
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

from app.analyzer import analyze_pcap

from .scenarios import all_scenarios

ROOT = Path(__file__).resolve().parents[2]


def evaluate() -> tuple[dict, list[dict]]:
    stats: dict[str, dict[str, int]] = defaultdict(lambda: {"tp": 0, "fp": 0, "fn": 0, "tn": 0})
    rows = []
    with tempfile.TemporaryDirectory(prefix="netsentinel-eval-") as tmp:
        for sc in all_scenarios():
            path = Path(tmp) / f"{sc.name}.pcap"
            sc.build().write(str(path))
            result = analyze_pcap(path)
            found = {f["kind"] for f in result["findings"]}
            attacks = {f["kind"] for f in result["findings"] if f["assessment"] == "attack"}
            problems = []
            for kind in sc.expect:
                if kind in found:
                    stats[kind]["tp"] += 1
                else:
                    stats[kind]["fn"] += 1
                    problems.append(f"missed {kind}")
            for kind in sc.forbid:
                if kind in found:
                    stats[kind]["fp"] += 1
                    problems.append(f"false alarm {kind}")
                else:
                    stats[kind]["tn"] += 1
            if sc.forbid_attacks:
                for kind in attacks - sc.forbid:
                    stats[kind]["fp"] += 1
                    problems.append(f"false attack verdict {kind}")
            for kind, expected in sc.expect_assessment.items():
                got = {f["assessment"] for f in result["findings"] if f["kind"] == kind}
                if got and expected not in got:
                    problems.append(f"{kind} assessed {sorted(got)} not {expected}")
            rows.append({"scenario": sc.name, "description": sc.description, "found": sorted(found),
                         "unlabelled": sorted(found - sc.expect - sc.forbid),
                         "verdict": result["verdict"]["status"], "problems": problems,
                         "packets": result["packets_analyzed"]})
    return stats, rows


def _ratio(a: int, b: int) -> str:
    return f"{a / b:.2f}" if b else "n/a"


def report(stats: dict, rows: list[dict]) -> str:
    lines = ["# NetSentinel detection evaluation (synthetic scenarios)", "",
             "Generated by `python -m lab.evaluate`. Each scenario is a labelled synthetic capture "
             "(see `backend/lab/scenarios`). These results show that each rule behaves as designed on "
             "its positive and negative cases. They are **not** an estimate of real-world accuracy: "
             "the scenarios were written by the same team that wrote the detectors.", "",
             "## Per finding kind", "",
             "| Finding kind | TP | FN | FP | TN | Precision | Recall | F1 |",
             "|---|---:|---:|---:|---:|---:|---:|---:|"]
    total = {"tp": 0, "fp": 0, "fn": 0, "tn": 0}
    for kind in sorted(stats):
        s = stats[kind]
        for k in total:
            total[k] += s[k]
        p = s["tp"] / (s["tp"] + s["fp"]) if s["tp"] + s["fp"] else None
        r = s["tp"] / (s["tp"] + s["fn"]) if s["tp"] + s["fn"] else None
        f1 = 2 * p * r / (p + r) if p and r else None
        fmt = lambda v: f"{v:.2f}" if v is not None else "n/a"
        lines.append(f"| {kind} | {s['tp']} | {s['fn']} | {s['fp']} | {s['tn']} | {fmt(p)} | {fmt(r)} | {fmt(f1)} |")
    lines += ["", f"**Overall:** TP {total['tp']}, FN {total['fn']}, FP {total['fp']}, TN {total['tn']}, "
                  f"precision {_ratio(total['tp'], total['tp'] + total['fp'])}, "
                  f"recall {_ratio(total['tp'], total['tp'] + total['fn'])}.", "",
              "## Per scenario", "", "| Scenario | Packets | Verdict | Reported kinds | Problems |",
              "|---|---:|---|---|---|"]
    for row in rows:
        lines.append(f"| `{row['scenario']}` | {row['packets']} | {row['verdict']} | "
                     f"{', '.join(row['found']) or '-'} | {'; '.join(row['problems']) or 'none'} |")
    failures = [r for r in rows if r["problems"]]
    lines += ["", f"{len(rows)} scenarios, {len(failures)} with problems."]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true", help="write docs/EVALUATION.md")
    args = parser.parse_args()
    stats, rows = evaluate()
    text = report(stats, rows)
    print(text)
    if args.write:
        out = ROOT / "docs" / "EVALUATION.md"
        out.parent.mkdir(exist_ok=True)
        out.write_text(text, encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
